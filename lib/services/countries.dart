// Country reference data for the profile. The chosen country sets the phone
// code, the currency and the timezone that every time and price in the app is
// shown in.

import 'package:timezone/timezone.dart' as tz;

class TimezoneInfo {
  const TimezoneInfo(this.id, this.offset);

  /// IANA id, e.g. `Asia/Kolkata`.
  final String id;

  /// Display offset, e.g. `GMT+5:30`.
  final String offset;

  String get label => '$id ($offset)';

  /// The real offset at the instant [utc], daylight saving included (from
  /// the IANA rules); the listed [offset] when the rules don't know [id].
  Duration offsetAt(DateTime utc) => zoneOffsetAt(id, utc) ?? utcOffset;

  /// [offset] as a duration, e.g. `GMT+5:30` → 5h 30m. This is the zone's
  /// standard offset; use [offsetAt] for a given moment.
  Duration get utcOffset {
    final match = RegExp(r'GMT([+-])(\d{1,2}):(\d{2})').firstMatch(offset);
    if (match == null) return Duration.zero;
    final minutes = int.parse(match.group(2)!) * 60 + int.parse(match.group(3)!);
    return Duration(minutes: match.group(1) == '-' ? -minutes : minutes);
  }
}

/// [id]'s offset at the instant [utc] by the IANA rules, or null when the
/// rules aren't loaded or don't know [id].
Duration? zoneOffsetAt(String id, DateTime utc) {
  try {
    return tz.getLocation(id).timeZone(utc.millisecondsSinceEpoch).offset;
  } catch (_) {
    return null;
  }
}

/// An offset as the app shows it, e.g. `GMT+5:30` or `GMT+1:00`.
String gmtLabel(Duration offset) {
  final minutes = offset.inMinutes.abs();
  return 'GMT${offset.isNegative ? '-' : '+'}${minutes ~/ 60}:${(minutes % 60).toString().padLeft(2, '0')}';
}

/// The timezone a user sees times in: their profile's, or this device's when
/// none is set. Offsets follow daylight saving, so a moment shows at the
/// clock time it really has on its own date.
///
/// "Wall" times are clock times in this zone, kept as UTC DateTimes (as the
/// rest of the app does) so the device's own zone never shifts them.
class UserZone {
  const UserZone(this.info);

  /// The profile's zone; null for this device's.
  final TimezoneInfo? info;

  /// The offset at the instant [utc].
  Duration offsetAt(DateTime utc) => info?.offsetAt(utc) ?? utc.toUtc().toLocal().timeZoneOffset;

  /// The offset right now.
  Duration get offset => offsetAt(DateTime.now().toUtc());

  /// The clock time of the instant [utc] in this zone.
  DateTime wall(DateTime utc) => utc.toUtc().add(offsetAt(utc));

  /// The instant of the clock time [wall] in this zone.
  DateTime toUtc(DateTime wall) {
    final at = DateTime.utc(wall.year, wall.month, wall.day, wall.hour, wall.minute, wall.second);
    final first = at.subtract(offsetAt(at));
    final second = offsetAt(first);
    return at.subtract(second);
  }

  /// The zone with its offset at the instant [utc], e.g.
  /// `Europe/Dublin (GMT+1:00)`.
  String labelAt(DateTime utc) {
    final zone = info;
    if (zone == null) return 'this device\'s time (${utc.toUtc().toLocal().timeZoneName})';
    return '${zone.id} (${gmtLabel(zone.offsetAt(utc))})';
  }

  /// The zone with its offset right now.
  String get label => labelAt(DateTime.now().toUtc());
}

class CountryInfo {
  const CountryInfo({
    required this.name,
    required this.iso,
    required this.dialCode,
    required this.phoneDigits,
    int? minPhoneDigits,
    required this.currencyCode,
    required this.currencySymbol,
    required this.timezones,
    this.cities = const [],
  }) : minPhoneDigits = minPhoneDigits ?? phoneDigits;

  final String name;

  /// ISO 3166-1 alpha-2 code, e.g. `IN`.
  final String iso;
  final String dialCode;

  /// Length of a national number, without the country code (the longest,
  /// where lengths vary).
  final int phoneDigits;

  /// The shortest national number; the same as [phoneDigits] where every
  /// number has one length.
  final int minPhoneDigits;
  final String currencyCode;
  final String currencySymbol;
  final List<TimezoneInfo> timezones;

  /// Suggested cities; any city can be typed in.
  final List<String> cities;

  String get currencyLabel => '$currencyCode ($currencySymbol)';

  /// Whether a national number of [length] digits fits this country.
  bool phoneFits(int length) => length >= minPhoneDigits && length <= phoneDigits;

  /// E.g. "10-digit" or "8–10 digit".
  String get phoneLengthLabel =>
      minPhoneDigits == phoneDigits ? '$phoneDigits-digit' : '$minPhoneDigits–$phoneDigits digit';
}

