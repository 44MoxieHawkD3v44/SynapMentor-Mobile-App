  static CountryInfo? byName(String? name) => all.where((c) => c.name == name).firstOrNull;

  /// Matches a country name or ISO code as the API returns it.
  static CountryInfo? find(String? value) {
    final v = value?.trim().toLowerCase();
    if (v == null || v.isEmpty) return null;
    return all.where((c) => c.name.toLowerCase() == v || c.iso.toLowerCase() == v).firstOrNull;
  }
